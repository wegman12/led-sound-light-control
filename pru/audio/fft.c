/* Initialize FFT buffer from real samples
 * Converts real samples to complex format and applies bit-reversal
 */
void fft_init(fft_buffer_t *fft_buf, const int16_t *input_samples) {
    uint16_t i, rev_i;

    /* Load samples with bit-reversal permutation */
    for (i = 0; i < FFT_SIZE; i++) {
        rev_i = bit_reverse_10(i);
        fft_buf->data[rev_i].real = input_samples[i];
        fft_buf->data[rev_i].imag = 0;  /* Imaginary part is zero for real input */
    }
}

/* Compute 1024-point FFT using Radix-2 Cooley-Tukey algorithm
 * Input: Complex samples in fft_buf (already bit-reversed)
 * Output: FFT result in-place in fft_buf
 */
void fft_compute(fft_buffer_t *fft_buf) {
    uint16_t stage, group, pair, span, offset;
    uint16_t twiddle_index, twiddle_step;
    complex_q15_t temp, w, u, t;

    /* Iterate through all FFT stages (log2(N) = 10 stages) */
    for (stage = 1; stage <= FFT_LOG2_SIZE; stage++) {
        /* Number of butterfly pairs per group in this stage */
        span = 1 << (stage - 1);  /* 2^(stage-1) */

        /* Distance between butterfly pairs */
        offset = 1 << stage;      /* 2^stage */

        /* Twiddle factor step for this stage */
        twiddle_step = 1 << (FFT_LOG2_SIZE - stage);

        /* Process all butterfly groups in this stage */
        for (group = 0; group < FFT_SIZE; group += offset) {
            twiddle_index = 0;

            /* Process all butterfly pairs in this group */
            for (pair = 0; pair < span; pair++) {
                uint16_t i = group + pair;
                uint16_t j = i + span;

                /* Get twiddle factor */
                w = twiddle_factors[twiddle_index];

                /* Butterfly operation:
                 * u = data[i]
                 * t = w * data[j]
                 * data[i] = u + t
                 * data[j] = u - t
                 */
                u = fft_buf->data[i];
                t = complex_mul_q15(w, fft_buf->data[j]);

                fft_buf->data[i].real = u.real + t.real;
                fft_buf->data[i].imag = u.imag + t.imag;

                fft_buf->data[j].real = u.real - t.real;
                fft_buf->data[j].imag = u.imag - t.imag;

                twiddle_index += twiddle_step;
            }
        }
    }
}

/* Calculate magnitude squared of complex number
 * Returns: |c|^2 = real^2 + imag^2 (in Q15 format, scaled to uint32)
 * This avoids the square root operation for efficiency
 */
uint32_t fft_magnitude_squared(complex_q15_t c) {
    int32_t real_sq = (int32_t)c.real * (int32_t)c.real;
    int32_t imag_sq = (int32_t)c.imag * (int32_t)c.imag;
    return (uint32_t)(real_sq + imag_sq);
}

/* Integer square root using Newton's method
 * Returns: sqrt(n) approximation
 */
static uint32_t isqrt(uint32_t n) {
    uint32_t x, y;

    if (n == 0) return 0;

    /* Initial guess: start with the value itself shifted right */
    x = n;
    y = (x + 1) >> 1;

    /* Newton's method: iterate until convergence (max 5 iterations is enough) */
    while (y < x) {
        x = y;
        y = (x + n / x) >> 1;
    }

    return x;
}

/* Calculate magnitude of complex number
 * Returns: |c| = sqrt(real^2 + imag^2)
 * More linear response to signal strength compared to magnitude squared
 */
uint32_t fft_magnitude(complex_q15_t c) {
    uint32_t mag_sq = fft_magnitude_squared(c);
    return isqrt(mag_sq);
}
